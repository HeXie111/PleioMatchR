#' PleioMatchR: Diagnostic Tools for Cross-Trait GWAS Sharing
#'
#' PleioMatchR provides a matched-control, permutation-based framework to
#' answer four questions about a predefined set of trait-associated loci in a
#' second GWAS: (1) is there association enrichment? (2) are effect directions
#' consistent, random, or antagonistic? (3) does pathway stratification reveal
#' internally consistent subgroups? (4) are the results robust to
#' cross-ancestry allele-frequency drift and control-matching artefacts?
#'
#' All output is association-level evidence.  The package does not estimate
#' causal effects and does not correct cross-ancestry LD-tag flipping; it
#' diagnoses potential bias so that users can make an informed decision.
#'
#' @keywords internal
